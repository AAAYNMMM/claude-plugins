/**
 * 网关后台守护服务管理脚本 (start / stop / restart / status)
 */

import { spawn, execSync } from 'node:child_process'
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { homedir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { STATUS_FILE } from '../src/core/config.ts'

const __dirname = dirname(fileURLToPath(import.meta.url))
const rootDir = join(__dirname, '..')
const command = process.argv[2] ?? 'status'

const STARTUP_DIR = join(
  process.env.APPDATA || join(homedir(), 'AppData', 'Roaming'),
  'Microsoft',
  'Windows',
  'Start Menu',
  'Programs',
  'Startup'
)
const VBS_PATH = join(STARTUP_DIR, 'AgentGatewayDaemon.vbs')
const OLD_VBS_PATH = join(STARTUP_DIR, 'ClaudeWorkBuddyGateway.vbs')

function killPort43119() {
  try {
    const out = execSync('netstat -ano | findstr :43119', { encoding: 'utf8' })
    const lines = out.trim().split('\n')
    for (const line of lines) {
      const parts = line.trim().split(/\s+/)
      const pid = parts[parts.length - 1]
      if (pid && /^\d+$/.test(pid) && pid !== '0') {
        try {
          execSync(`taskkill /F /PID ${pid}`)
        } catch {}
      }
    }
  } catch {}
}

function killExistingDaemons() {
  try {
    execSync('wmic process where "name=\'wscript.exe\' and commandline like \'%Gateway%\'" call terminate', { stdio: 'ignore' })
  } catch {}
  killPort43119()
}

if (command === 'status') {
  try {
    const res = await fetch('http://127.0.0.1:43119/health', { signal: AbortSignal.timeout(1500) })
    if (res.ok) {
      process.stdout.write('✓ 网关服务正在后台稳定运行 (端口 :43119 正常响应)。\n')
      process.exit(0)
    }
  } catch {}
  process.stdout.write('网关服务当前未运行。\n')
} else if (command === 'stop') {
  killExistingDaemons()
  rmSync(VBS_PATH, { force: true })
  rmSync(OLD_VBS_PATH, { force: true })
  rmSync(STATUS_FILE, { force: true })
  process.stdout.write('✓ 已完全停止网关服务并清理后台自启守护进程。\n')
} else if (command === 'start' || command === 'restart') {
  killExistingDaemons()
  rmSync(OLD_VBS_PATH, { force: true })

  const serverJs = join(rootDir, 'dist', 'server.js')
  const nodeExe = process.execPath

  // 生成开机与后台循环守护脚本
  const vbsContent = [
    `' Generated by agent-gateway: run gateway in hidden background and restart on crash`,
    `Set sh = CreateObject("WScript.Shell")`,
    `node = "${nodeExe}"`,
    `server = "${serverJs}"`,
    `cmd = Chr(34) & node & Chr(34) & " " & Chr(34) & server & Chr(34)`,
    `Do`,
    `  code = sh.Run(cmd & " serve", 0, True)`,
    `  If code = 0 Then Exit Do`,
    `  WScript.Sleep 3000`,
    `Loop`,
  ].join('\r\n')

  writeFileSync(VBS_PATH, vbsContent, 'utf8')

  // 立即通过 PowerShell 启动脱离后台的 VBS 守护
  try {
    execSync(`powershell -NoProfile -Command "Start-Process wscript.exe -ArgumentList '${VBS_PATH}'"`, { stdio: 'ignore' })
  } catch {
    spawn('wscript.exe', [VBS_PATH], { detached: true, stdio: 'ignore' }).unref()
  }

  process.stdout.write('✓ 网关服务与后台守护进程已成功启动！\n')
}
