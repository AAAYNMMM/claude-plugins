/**
 * agent-gateway 打包脚本：使用 esbuild 将 src/main.ts 打包为单个 ESM 运行时文件。
 */

import { build } from 'esbuild'
import { cpSync, existsSync, mkdirSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const dist = join(root, 'dist')

rmSync(dist, { recursive: true, force: true })
mkdirSync(dist, { recursive: true })

await build({
  entryPoints: [join(root, 'src', 'main.ts')],
  outfile: join(dist, 'server.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  sourcemap: false,
  external: ['@deepseek-ai/*'],
  banner: {
    js: '#!/usr/bin/env node\n// agent-gateway: generated by build.mjs. Do not edit by hand.',
  },
  logLevel: 'info',
})

// 复制原生辅助脚本（WorkBuddy 模块需要的 turing-sdk 子进程脚本）
const vendorNative = join(root, 'src', 'modules', 'workbuddy', 'vendor', 'native')
if (existsSync(vendorNative)) {
  cpSync(vendorNative, join(root, 'native'), { recursive: true })
}

// 复制反重力凭据读取脚本到 dist/
const agyPs = join(root, 'src', 'modules', 'antigravity', 'read-cred.ps1')
if (existsSync(agyPs)) {
  cpSync(agyPs, join(dist, 'read-cred.ps1'))
}

process.stdout.write('built dist/server.js successfully\n')
