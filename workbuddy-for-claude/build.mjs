/**
 * 构建脚本：用 esbuild 把 src/main.ts 及其引用到的插件源码打成单个 ESM 文件。
 *
 * 为什么要打包：插件源码是 TypeScript，并且用了 Node 的类型剥离模式不支持的
 * “构造函数参数属性”写法，所以不能直接 node xxx.ts 运行。esbuild 一次转译完成，
 * 产物 dist/server.js 只依赖 Node 内置模块，部署时不需要 node_modules。
 *
 * 另外把 vendor/native 复制到仓库根目录：插件里的 turing-sdk 用
 * `../native/turing-sdk`（相对模块自身位置）定位子进程脚本，产物在 dist/ 下，
 * 于是它解析到的正是仓库根目录的 native/。
 */

import { build } from 'esbuild'
import { cpSync, mkdirSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const dist = join(root, 'dist')

rmSync(dist, { recursive: true, force: true })
mkdirSync(dist, { recursive: true })

await build({
  entryPoints: [join(root, 'src', 'main.ts')],
  outfile: join(dist, 'server.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  sourcemap: false,
  // 插件里有一处 try/catch 包住的动态 import('@deepseek-ai/...')：那是宿主环境才有的
  // 可选依赖，打包时不该去找它，交给运行期解析。
  external: ['@deepseek-ai/*'],
  banner: {
    js: '#!/usr/bin/env node\n// claude-workbuddy: generated by build.mjs. Do not edit by hand.',
  },
  logLevel: 'info',
})

// 运行期的原生辅助脚本（插件自带的 turing-sdk 子进程入口）。
cpSync(join(root, 'vendor', 'native'), join(root, 'native'), { recursive: true })

process.stdout.write('built dist/server.js\n')
