# 把 WorkBuddy 网关安装到 Claude Code（用户级设置）。
#
# 做的事：
#   1. 首次运行时构建 dist/server.js；
#   2. 读取（或创建）~/.workbuddy-claude/config.json，并确认默认模型；
#   3. 后台启动网关；
#   4. 把 ANTHROPIC_* 环境变量写进 ~/.claude/settings.json（可用 uninstall.ps1 完整撤销）；
#   5. 仅在显式传 -Autostart 时，把网关启动脚本放进“启动”文件夹，让它在每次登录时自动运行。
#
# 用法：
#   powershell -ExecutionPolicy Bypass -File install.ps1
#   powershell -ExecutionPolicy Bypass -File install.ps1 -Model kimi-k3-1 -SmallModel deepseek-v4.1-flash
#   powershell -ExecutionPolicy Bypass -File install.ps1 -Autostart

param(
  [string]$Model = '',
  [string]$SmallModel = '',
  [switch]$Project,
  [switch]$Autostart,
  [switch]$AppProvider,
  [string]$ProjectDir = (Get-Location).Path
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$homeDir = Join-Path $env:USERPROFILE '.workbuddy-claude'

Write-Host '=== WorkBuddy for Claude Code ===' -ForegroundColor Cyan

# 1. 构建产物
if (-not (Test-Path (Join-Path $root 'dist\server.js'))) {
  Write-Host '首次运行：正在安装构建依赖并编译…'
  Push-Location $root
  npm install --no-audit --no-fund
  npm run build
  Pop-Location
}

$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { throw '找不到 node.exe，请先安装 Node.js 22.18 或更高版本。' }

# 2. 配置与模型
if ($Model -ne '') {
  & $node (Join-Path $root 'dist\server.js') set defaultModel $Model | Out-Null
}
if ($SmallModel -ne '') {
  & $node (Join-Path $root 'dist\server.js') set smallModel $SmallModel | Out-Null
}

Write-Host '正在读取 WorkBuddy 账号与模型目录…'
& $node (Join-Path $root 'dist\server.js') models | Out-Host

$config = Get-Content (Join-Path $homeDir 'config.json') -Raw | ConvertFrom-Json
if ($config.defaultModel -eq '') {
  & $node (Join-Path $root 'dist\server.js') set defaultModel deepseek-v4-pro | Out-Null
  $config = Get-Content (Join-Path $homeDir 'config.json') -Raw | ConvertFrom-Json
}
if ($config.smallModel -eq '') {
  & $node (Join-Path $root 'dist\server.js') set smallModel deepseek-v4.1-flash | Out-Null
}

# 3. 后台启动：用 VBScript 隐藏窗口，避免每次登录弹一个控制台
$launcher = Join-Path $homeDir 'start-gateway.vbs'
$server = Join-Path $root 'dist\server.js'
$vbs = @"
' Generated by install.ps1: run the gateway hidden; restart on abnormal exit.
Set sh = CreateObject("WScript.Shell")
node = "$node"
srv = "$server"
cmd = Chr(34) & node & Chr(34) & " " & Chr(34) & srv & Chr(34)
Do
  code = sh.Run(cmd & " serve", 0, True)
  If code = 0 Then Exit Do
  WScript.Sleep 5000
Loop
"@
Set-Content -Path $launcher -Value $vbs -Encoding ASCII

$running = $false
try {
  $health = Invoke-WebRequest -UseBasicParsing -TimeoutSec 2 -Uri "http://127.0.0.1:$($config.port)/health"
  $running = $health.StatusCode -eq 200
} catch { $running = $false }

if (-not $running) {
  Write-Host '正在后台启动网关…'
  if ($Autostart) {
    # 走 VBS 启动器：既隐藏窗口，也带着崩溃重启的看护。
    Start-Process -FilePath 'wscript.exe' -ArgumentList "`"$launcher`"" -WindowStyle Hidden
  } else {
    Start-Process -FilePath $node -ArgumentList @($server, 'serve') -WindowStyle Hidden
  }
  Start-Sleep -Seconds 4
}

# 4. 写入 Claude Code 设置
if ($Project) {
  Push-Location $root
  & $node (Join-Path $root 'scripts\settings.mjs') enable --project $ProjectDir
  Pop-Location
} else {
  Push-Location $root
  & $node (Join-Path $root 'scripts\settings.mjs') enable
  Pop-Location
}

# 5. 登录时自动启动（默认关闭，必须显式传 -Autostart）
if ($Autostart) {
  $startup = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Startup'
  New-Item -ItemType Directory -Force -Path $startup | Out-Null
  Copy-Item -Path $launcher -Destination (Join-Path $startup 'ClaudeWorkBuddyGateway.vbs') -Force
  Write-Host '已安装登录自启动（启动文件夹：ClaudeWorkBuddyGateway.vbs）。'
} else {
  Write-Host '未安装登录自启动；需要时用 -Autostart 参数重跑本脚本。'
}

# 5.5 桌面 App 的模型列表（默认关闭，因为这会改 App 自己的 provider 配置）
if ($AppProvider) {
  Push-Location $root
  & $node (Join-Path $root 'scripts\app-provider.mjs') apply
  Pop-Location
  Write-Host '已把桌面 App 的模型提供方指向本网关；重启 App 后模型列表会出现 DeepSeek 与 WorkBuddy 两组模型。'
} else {
  Write-Host '未修改桌面 App 的 provider 配置；需要时用 -AppProvider 参数重跑本脚本，或运行 应用模型列表.bat。'
}

# 6. 斜杠命令
$commandsDir = Join-Path $env:USERPROFILE '.claude\commands'
New-Item -ItemType Directory -Force -Path $commandsDir | Out-Null
$statusCmd = Join-Path $commandsDir 'workbuddy-status.md'
$modelsCmd = Join-Path $commandsDir 'workbuddy-models.md'
Set-Content -Path $statusCmd -Encoding UTF8 -Value @"
---
description: 查看 WorkBuddy 账号、积分和当前默认模型
allowed-tools: Bash(node:*)
---
运行下面的命令，把输出原样展示给我：

!``$node "$server" status``
"@
Set-Content -Path $modelsCmd -Encoding UTF8 -Value @"
---
description: 列出 WorkBuddy 目录里可用的模型及其积分倍率
allowed-tools: Bash(node:*)
---
运行下面的命令，把输出原样展示给我：

!``$node "$server" models``
"@

Write-Host ''
Write-Host '安装完成。' -ForegroundColor Green
Write-Host "  网关地址：http://127.0.0.1:$($config.port)"
Write-Host "  默认模型：$($config.defaultModel)"
Write-Host '  设置文件：' -NoNewline; Write-Host (Join-Path $env:USERPROFILE '.claude\settings.json')
Write-Host '  请新开一个 Claude Code 会话使设置生效（当前已打开的会话不受影响）。'
Write-Host ''
Write-Host '临时切回原生 Claude：powershell -ExecutionPolicy Bypass -File disable.ps1'
Write-Host '完整卸载：powershell -ExecutionPolicy Bypass -File uninstall.ps1'
